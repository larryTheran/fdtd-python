#!/usr/bin/env python3
"""Verify saved outputs, then generate the experiment catalog and result gallery."""
from pathlib import Path
from dataclasses import asdict
import json
import sys
import xml.etree.ElementTree as ET
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from run_all import experiments


def main():
    cases = experiments()
    catalog = ["# Experiment catalog", "", "Each file runs independently. Edit its CONFIG block or use `--help`. "
               "The main thesis is the 118-page root PDF; references below use printed page numbers.", "",
               "| ID / script | Experiment | Thesis / original source | Grid | Steps |", "|---|---|---|---|---|"]
    gallery = ["# Simulation results", "", "All listed outputs were generated by the Python simulations. "
               "Select an animation to see the field evolve, or inspect static figures and saved numerical diagnostics.", "",
               "[Run instructions](../README.md) · [Experiment catalog](../docs/EXPERIMENTS.md) · "
               "[Validation](../docs/VALIDATION.md) · [Corrections](../docs/NUMERICS.md)", ""]
    validation = ["# Validation results", "", "The checks below refer to saved runs produced in this workspace. "
                  "The code was verified against analytical physics and numerical invariants; MATLAB/Octave was not executed.", ""]
    tree = ET.parse(ROOT/"results/tests.xml")
    suites = tree.getroot().findall("testsuite")
    tests = sum(int(s.attrib.get("tests", 0)) for s in suites)
    failures = sum(int(s.attrib.get("failures", 0))+int(s.attrib.get("errors", 0)) for s in suites)
    assert failures == 0, "Automated tests failed"
    validation.extend([f"**{tests} automated tests passed, with no failures.** "
                       "The suite covers all independent scripts plus the numerical and CLI/GIF checks. "
                       "See `results/tests.log` and `results/tests.xml`.", "",
                       "## Physics checks", "",
                       "- Vacuum pulse speed and TF/SF directionality.",
                       "- Absorbing versus reflecting 1D boundaries and periodic propagation.",
                       "- Fresnel amplitude/sign at an index step and analytical Fabry-Perot slab spectra.",
                       "- 1D and 2D lossless spectral power balance.",
                       "- Ohmic attenuation and agreement with the integral-current update.",
                       "- Dimensional distinction between optical and centimeter-grid loss.",
                       "- 2D PML pulse decay, x/y symmetry, rectangular meshes and periodic translation.",
                       "- Plane TF/SF uniformity, aperture cell counts, Fresnel regime and far-field envelope.",
                       "- Refraction angle from the simulated phasor versus Snell's law.",
                       "- Invalid-input rejection, direct script launch from another directory, saved arrays and animated GIF frames.", "",
                       "## Saved full runs", "",
                       "A successful run here means finite fields and valid output artifacts. It does not imply "
                       "every geometry is independently converged in grid spacing, boundary thickness and run duration.", "",
                       "| Experiment | Steps | Final / peak domain energy proxy | Maximum abs(1-R-T), if spectral |", "|---|---:|---:|---:|"])
    manifest, verified = [], []
    for path, c in cases:
        out = ROOT/"results"/c.name
        config = json.loads((out/"config.json").read_text())
        diag = json.loads((out/"diagnostics.json").read_text())
        assert config["steps"] == c.steps
        for key, value in config.items():
            expected = asdict(c)[key]
            # JSON changes tuples into lists.
            assert value == json.loads(json.dumps(expected)), (c.name, key)
        with np.load(out/"data.npz", allow_pickle=False) as r:
            assert np.isfinite(r["e"]).all() and np.isfinite(r["energy"]).all()
            assert r["snapshot_steps"][-1] == c.steps
            assert len(r["energy"]) == c.steps
            assert r["frames"].shape[0] > 1
            if "spectral_valid" in r:
                ok = r["spectral_valid"]
                assert ok.any()
                assert np.isfinite(r["reflectance"][ok]).all()
                assert np.isfinite(r["transmittance"][ok]).all()
            shape = " x ".join(str(n) for n in r["e"].shape)
        images = sorted(out.glob("*.png"))
        for image in images:
            with Image.open(image) as im:
                im.verify()
        with Image.open(out/"animation.gif") as im:
            frames = im.n_frames
            assert frames > 1
            for k in [0, frames//2, frames-1]:
                im.seek(k)
                im.convert("RGB").load()
        manifest.append(dict(script=str(path.relative_to(ROOT)), **asdict(c)))
        verified.append(dict(experiment=c.name, status="verified", gif_frames=frames,
                             png_count=len(images), **diag))
        catalog.append(f"| [{c.name}](../{path.relative_to(ROOT)}) | {c.title} | {c.thesis} | {shape} | {c.steps} |")
        residual = f"{diag['max_abs_spectral_residual']:.5g}" if "max_abs_spectral_residual" in diag else "—"
        validation.append(f"| {c.name} | {c.steps} | {diag['remaining_energy_fraction']:.5g} | {residual} |")
        gallery.extend([f"## {c.name} — {c.title}", "", c.thesis, "",
                        f"[Animation]({c.name}/animation.gif) · [Field snapshots]({c.name}/fields.png) · "
                        f"[Diagnostics]({c.name}/diagnostics.json) · [Python code](../{path.relative_to(ROOT)})", ""])
        # A single static thumbnail per experiment keeps the gallery fast to open.
        gallery.extend([f"![{c.title}]({c.name}/fields.png)", ""])
        if (out/"spectra.png").exists():
            gallery.append(f"[Reflection/transmission spectrum]({c.name}/spectra.png)\n")
        if (out/"detector.png").exists():
            gallery.append(f"[Diffraction detector]({c.name}/detector.png)\n")
    validation.extend(["", f"**{len(verified)} full default experiments verified**, including PNG decoding, "
                       "multi-frame GIF decoding, finite numerical fields and saved parameter consistency.", "",
                       "Large energy fractions are expected for continuous sources, reflecting or periodic domains. "
                       "For lossy materials, a nonzero spectral residual is physically expected; the residual column "
                       "is not a numerical-error score for such cases. Pulse energy in a mixed PML/periodic domain "
                       "can persist in modes traveling along the periodic direction.", "",
                       "## Refraction measurements", "", "These are local phase-gradient diagnostics from finite beams, "
                       "not fits to the thesis figures. Their window is specified in `fdtd/analysis.py`.", "",
                       "| Experiment | Interface row | Snell angle | Measured phase angle |", "|---|---:|---:|---:|"])
    for item in verified:
        for ray in item.get("refraction", []):
            prediction, measurement = ray["snell_angle_deg"], ray["measured_phase_angle_deg"]
            p = f"{prediction:.3f}°" if prediction is not None else "TIR"
            m = f"{measurement:.3f}°" if measurement is not None else "unavailable"
            validation.append(f"| {item['experiment']} | {ray['interface_y']} | {p} | {m} |")
    validation.extend(["", "## Practical limits", "",
                       "The main free-space, boundary, dielectric and diffraction implementations have independent "
                       "physics tests. The supplemental waveguide is verified to run and guide a mode around the bend, "
                       "but no quantitative coupling-efficiency or 3D effective-index convergence result is claimed. "
                       "The supplementary first-order Mur source is not a port of the draft's higher-order boundary. "
                       "Periodic slit examples represent aperture arrays. Optical losses below numerical residuals "
                       "cannot be estimated reliably from 1-R-T on these demonstration grids.", "",
                       "The periodic material stack was checked at 16000, 32000 and 64000 steps; its maximum "
                       "spectral residual fell from approximately 8.75% to 0.522% and 0.436%. "
                       "The final saved run uses 64000 steps. This is time-record convergence, not a complete mesh-convergence study.", ""])
    (ROOT/"docs/EXPERIMENTS.md").write_text("\n".join(catalog)+"\n")
    (ROOT/"docs/experiments.json").write_text(json.dumps(manifest, indent=2)+"\n")
    (ROOT/"results/README.md").write_text("\n".join(gallery))
    (ROOT/"docs/VALIDATION.md").write_text("\n".join(validation))
    (ROOT/"results/verified_runs.json").write_text(json.dumps(verified, indent=2)+"\n")
    print(f"Verified {len(verified)} full runs and {tests} tests; reports generated")


if __name__ == "__main__":
    main()
